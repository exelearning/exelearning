#!/usr/bin/env node
/**
 * Extract icons from TinyMCE and create ProseMirrorIcons.js
 */
const fs = require('fs');
const path = require('path');

const projectRoot = path.resolve(__dirname, '..');
const tinymceIconsPath = path.join(projectRoot, 'public/libs/tinymce_5/js/tinymce/icons/default/icons.min.js');
const outputPath = path.join(projectRoot, 'public/app/prosemirror/ProseMirrorIcons.js');

const content = fs.readFileSync(tinymceIconsPath, 'utf-8');

// Parse icons - handle both "key" and key without quotes
const allIcons = {};

// Match patterns like: "align-center":'<svg...' OR bold:'<svg...'
const regex1 = /"([^"]+)":'([^']+)'/g;
const regex2 = /,([a-z]+):'([^']+)'/g;

let match;
while ((match = regex1.exec(content)) !== null) {
    allIcons[match[1]] = match[2];
}
while ((match = regex2.exec(content)) !== null) {
    allIcons[match[1]] = match[2];
}

console.log(`Found ${Object.keys(allIcons).length} TinyMCE icons`);

// Map our button names to TinyMCE icon names
const iconMapping = {
    'bold': 'bold',
    'italic': 'italic',
    'underline': 'underline',
    'strikethrough': 'strike-through',
    'subscript': 'subscript',
    'superscript': 'superscript',
    'code': 'code-sample',
    'alignleft': 'align-left',
    'aligncenter': 'align-center',
    'alignright': 'align-right',
    'alignjustify': 'align-justify',
    'bullist': 'unordered-list',
    'numlist': 'ordered-list',
    'undo': 'undo',
    'redo': 'redo',
    'link': 'link',
    'unlink': 'unlink',
    'image': 'image',
    'embed': 'embed-page',
    'media': 'embed',
    'table': 'table',
    'tabledelete': 'table-delete-table',
    'tablemerge': 'table-merge-cells',
    'tablesplit': 'table-split-cells',
    'tablerowbefore': 'table-insert-row-above',
    'tablerowafter': 'table-insert-row-after',
    'tablerowdelete': 'table-delete-row',
    'tablecolbefore': 'table-insert-column-before',
    'tablecolafter': 'table-insert-column-after',
    'tablecoldelete': 'table-delete-column',
    'hr': 'horizontal-rule',
    'removeformat': 'remove-formatting',
    'paste': 'paste',
    'pastespecial': 'paste-text',
    'pastetext': 'paste-text',
    'copy': 'copy',
    'cut': 'cut-row',
    'fullscreen': 'fullscreen',
    'sourcecode': 'sourcecode',
    'forecolor': 'color-picker',
    'backcolor': 'highlight-bg-color',
    'charmap': 'insert-character',
    'emoticons': 'emoji',
    'anchor': 'bookmark',
    'blockquote': 'quote',
    'quote': 'quote',
    'outdent': 'outdent',
    'indent': 'indent',
    'print': 'print',
    'help': 'help',
    'upload': 'upload',
    'search': 'search',
    'newdocument': 'new-document',
    'save': 'save',
    'preview': 'preview',
    'template': 'template',
    'datetime': 'insert-time',
    'chevrondown': 'chevron-down',
    'chevronright': 'chevron-right',
    'definitionlist': 'list-bull-default',
    'rtl': 'rtl',
    'ltr': 'ltr',
    'html': 'sourcecode',
    'clearfloat': 'remove-formatting',
    'selectall': 'select-all',
    'warning': 'warning',
    'info': 'info',
    'checkmark': 'checkmark',
    'visualchars': 'visualchars',
    'visualblocks': 'visualblocks',
};

// Generate the icon object
const icons = {};
const missing = [];
for (const [ourName, tinyName] of Object.entries(iconMapping)) {
    if (allIcons[tinyName]) {
        icons[ourName] = allIcons[tinyName];
    } else {
        missing.push({ ourName, tinyName });
    }
}

if (missing.length > 0) {
    console.log('Missing icons:', missing.map(m => m.tinyName).join(', '));
}

// Generate JS file content
const jsContent = `/**
 * ProseMirror Icons - Extracted from TinyMCE
 *
 * SVG icons matching TinyMCE's default icon set for visual consistency.
 * Auto-generated by scripts/extract-tinymce-icons.js
 */
(function() {
    'use strict';

    const icons = ${JSON.stringify(icons, null, 8)};

    /**
     * Get SVG icon by name
     * @param {string} name - Icon name
     * @returns {string|null} - SVG string or null if not found
     */
    function getIcon(name) {
        return icons[name] || null;
    }

    /**
     * Create icon element
     * @param {string} name - Icon name
     * @returns {HTMLElement|null} - Span element with SVG or null
     */
    function createIconElement(name) {
        const svg = getIcon(name);
        if (!svg) return null;

        const span = document.createElement('span');
        span.className = 'tox-icon';
        span.innerHTML = svg;
        return span;
    }

    // Export
    window.ProseMirrorIcons = {
        icons,
        getIcon,
        createIconElement,
    };
})();
`;

fs.writeFileSync(outputPath, jsContent);
console.log(`Created ${outputPath} with ${Object.keys(icons).length} icons`);
